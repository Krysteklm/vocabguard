// One fixed signing key for every build (local or CI). Android only installs an update over the
// existing app when the signature matches, so a stable key means: no uninstalling, your words and
// settings stay, and the Accessibility permission survives updates.
val keystoreProperties = Properties().apply {
    val file = rootProject.file("keystore.properties")
    if (file.exists()) file.inputStream().use { load(it) }
}
val hasStableKey = keystoreProperties.getProperty("storeFile") != null

android {
    namespace = "com.vocabguard"
    compileSdk = 35

    defaultConfig {
        applicationId = "com.vocabguard"
        minSdk = 26
        targetSdk = 35
        // CI passes -PversionCode=<run number> so every build is a newer, installable update.
        versionCode = (project.findProperty("versionCode") as String?)?.toIntOrNull() ?: 3
        versionName = "1.2.0"
    }

    signingConfigs {
        if (hasStableKey) {
            create("stable") {
                storeFile = rootProject.file(keystoreProperties.getProperty("storeFile"))
                storePassword = keystoreProperties.getProperty("storePassword")
                keyAlias = keystoreProperties.getProperty("keyAlias")
                keyPassword = keystoreProperties.getProperty("keyPassword")
            }
        }
    }

    buildTypes {
        debug {
            if (hasStableKey) signingConfig = signingConfigs.getByName("stable")
        }
        release {
            isMinifyEnabled = true
            isShrinkResources = true
            proguardFiles(
                getDefaultProguardFile("proguard-android-optimize.txt"),
                "proguard-rules.pro",
            )
            if (hasStableKey) signingConfig = signingConfigs.getByName("stable")
        }
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }
    kotlinOptions { jvmTarget = "17" }
    buildFeatures { compose = true }
}

ksp {
